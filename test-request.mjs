import { createClient } from '@supabase/supabase-js';
import { readFileSync, writeFileSync } from 'fs';
import { resolve } from 'path';

// Load .env.local
const envContent = readFileSync('.env.local', 'utf-8');
const env = {};
for (const line of envContent.split('\n')) {
  const trimmed = line.trim();
  if (!trimmed || trimmed.startsWith('#')) continue;
  const eqIdx = trimmed.indexOf('=');
  if (eqIdx === -1) continue;
  const key = trimmed.slice(0, eqIdx).trim();
  let val = trimmed.slice(eqIdx + 1).trim();
  if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
    val = val.slice(1, -1);
  }
  env[key] = val;
}

// If we already have a session token and store ID from last run, use those
// Otherwise create new ones
let accessToken = '';
let storeId = '';

if (!accessToken) {
  const supabaseUrl = env.NEXT_PUBLIC_SUPABASE_URL;
  const serviceRoleKey = env.SUPABASE_SERVICE_ROLE_KEY;

  const supabase = createClient(supabaseUrl, serviceRoleKey, {
    auth: { autoRefreshToken: false, persistSession: false }
  });

  const email = 'test-vision-' + Date.now() + '@test.local';
  const password = 'Test123!';

  const { data: userData, error: signUpError } = await supabase.auth.admin.createUser({
    email, password, email_confirm: true
  });
  if (signUpError) { console.error('SIGNUP ERROR:', signUpError); process.exit(1); }

  const userId = userData.user.id;

  const { data: storeData, error: storeError } = await supabase
    .from('negozi')
    .insert({ owner_user_id: userId, nome: 'Test Store Vision', slug: 'test-store-vision-' + Date.now(), categoria: 'elettronica', attivo: true })
    .select()
    .single();
  if (storeError) { console.error('STORE ERROR:', storeError); process.exit(1); }

  storeId = storeData.id;

  const { data: signInData, error: signInError } = await supabase.auth.signInWithPassword({ email, password });
  if (signInError) { console.error('SIGNIN ERROR:', signInError); process.exit(1); }

  accessToken = signInData.session.access_token;

  // The Supabase SSR auth cookie name
  const projectRef = supabaseUrl.split('.')[0].split('//')[1];
  const authCookieName = `sb-${projectRef}-auth-token`;
  const authCookieValue = JSON.stringify({
    access_token: signInData.session.access_token,
    refresh_token: signInData.session.refresh_token,
    expires_in: 3600,
    expires_at: Math.floor(Date.now() / 1000) + 3600,
    token_type: 'bearer'
  });

  console.log('Auth cookie name:', authCookieName);
  console.log('Auth cookie value:', authCookieValue);

  // Save to file for reuse
  writeFileSync('test-session.json', JSON.stringify({
    accessToken,
    storeId,
    refreshToken: signInData.session.refresh_token,
    authCookieName,
    authCookieValue
  }, null, 2));
  console.log('Session saved to test-session.json');
}

