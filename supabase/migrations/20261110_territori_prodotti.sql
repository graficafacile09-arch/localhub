begin;

-- TERRITORI — sezione editoriale "Territorio".
--
-- Migration puramente ADDITIVA: non modifica né elimina colonne o tabelle
-- esistenti e non tocca alcun dato commerciale (prezzi, disponibilità,
-- ordini). Crea solo:
--   1. `territori`            — anagrafica delle dieci destinazioni;
--   2. `prodotto_territori`   — relazione prodotto ↔ territorio con i campi
--                               di provenienza documentata (fonte, ente,
--                               nota, data di verifica, stato).
--
-- La relazione NON si basa sulla città del negozio: `negozio_id` non viene
-- usato come prova di provenienza. Ogni riga dichiara esplicitamente la
-- fonte che documenta il legame.

create table if not exists public.territori (
  id          uuid primary key default gen_random_uuid(),
  slug        text not null unique,
  nome        text not null,
  gruppo      text not null check (gruppo in ('Parchi', 'Aree territoriali', 'Comuni')),
  ordine      integer not null default 0,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.prodotto_territori (
  id              bigint generated by default as identity primary key,
  prodotto_id     bigint not null references public.prodotti(id) on delete cascade,
  territorio_slug text not null references public.territori(slug) on update cascade on delete cascade,
  stato           text not null default 'da_confermare'
                    check (stato in ('registro', 'da_confermare')),
  fonte_url       text,
  ente            text,
  nota            text,
  verificato_il   date,
  created_at      timestamptz not null default now(),
  unique (prodotto_id, territorio_slug)
);

create index if not exists prodotto_territori_territorio_idx
  on public.prodotto_territori (territorio_slug);
create index if not exists prodotto_territori_prodotto_idx
  on public.prodotto_territori (prodotto_id);

alter table public.territori enable row level security;
alter table public.prodotto_territori enable row level security;

-- Lettura pubblica: sono dati editoriali già pubblicati sul sito.
-- La scrittura resta possibile solo con service role (bypassa RLS).
drop policy if exists "territori_lettura_pubblica" on public.territori;
create policy "territori_lettura_pubblica"
  on public.territori for select
  using (true);

drop policy if exists "prodotto_territori_lettura_pubblica" on public.prodotto_territori;
create policy "prodotto_territori_lettura_pubblica"
  on public.prodotto_territori for select
  using (true);

grant select on public.territori to anon, authenticated;
grant select on public.prodotto_territori to anon, authenticated;

